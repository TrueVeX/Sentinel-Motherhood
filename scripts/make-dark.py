"""Generate dark-theme overrides from the site's stylesheets.

For every top-level rule: light backgrounds -> dark teal surfaces, dark text -> light text,
teal/red text -> lighter tints, light borders -> dark borders. Rules whose background is an
accent (deep teal, teal, mint, gradients) are left alone, so buttons and dark sections keep
their look. Output: src/app/theme.css (imported after the other stylesheets).
"""
import re, sys, pathlib

ROOT = pathlib.Path(sys.argv[1])
FILES = ["src/app/globals.css", "src/app/pages.css", "src/app/home/landing.css"]
PREFIX = '[data-theme="dark"]'

VARS = {
    "var(--ivory)": (244, 247, 242), "var(--white)": (255, 255, 255), "white": (255, 255, 255),
    "var(--deep)": (18, 63, 70), "var(--teal)": (36, 124, 120), "var(--mint)": (168, 207, 195),
    "var(--ink)": (24, 59, 61), "var(--muted)": (99, 123, 120),
}

def rgb_of(value):
    v = value.strip().replace("!important", "").strip()
    if v in VARS:
        return VARS[v]
    m = re.fullmatch(r"#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})", v)
    if m:
        h = m.group(1)
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
    m = re.fullmatch(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)", v)
    if m:
        a = float(m.group(4)) if m.group(4) else 1.0
        if a < 0.5:
            return None  # mostly transparent: leave it
        return tuple(int(m.group(i)) for i in (1, 2, 3))
    return None

def lum(rgb):
    def ch(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b

def dark_bg(rgb, selector):
    l = lum(rgb)
    if l < 0.55:
        return None  # already dark or an accent: keep
    if re.search(r"(^|[\s,])(html|body)($|[\s,:])", selector):
        return "#0F2529"
    r, g, b = rgb
    if r > g + 12 and r > b:  # warm/pink warning surfaces
        return "#3A2723"
    if (r, g, b) in [(168, 207, 195)]:  # mint accent
        return None
    return "#17343A" if l > 0.9 else "#1E4148"

def dark_text(value):
    v = value.strip().replace("!important", "").strip()
    if v in ("var(--teal)", "#247C78", "#247c78"):
        return "#7FC4B6"
    rgb = rgb_of(v)
    if rgb is None:
        return None
    l = lum(rgb)
    r, g, b = rgb
    if r > g + 40 and l < 0.3:  # reds like #A4402F
        return "#F0A08F"
    if l < 0.12:
        return "#E6EFEB"
    if l < 0.45 and not (r > 200 and g > 200):
        return "#A9C0BA"
    return None

def top_level_rules(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j == -1:
            return
        head = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        if not head.startswith("@"):
            yield head, body
        i = k

def declarations(body):
    for part in body.split(";"):
        if ":" in part:
            prop, val = part.split(":", 1)
            yield prop.strip(), val.strip()

out = [
    "/* Generated by make_dark.py: dark theme overrides. Edit scripts/make-dark.py and run: python scripts/make-dark.py . */",
    f'{PREFIX} {{ color-scheme: dark; --ink: #E6EFEB; --muted: #A9C0BA; --line: #2C4D53; }}',
    f"{PREFIX} body {{ background: #0F2529; color: #E6EFEB; }}",
]
count = 0
for f in FILES:
    css = (ROOT / f).read_text(encoding="utf-8")
    for selector, body in top_level_rules(css):
        decls = list(declarations(body))
        new = []
        bg_kept_accent = False
        for prop, val in decls:
            if prop in ("background", "background-color"):
                rgb = rgb_of(val)
                imp = " !important" if "!important" in val else ""
                if rgb is None:
                    if "gradient" in val or "var(--deep)" in val or "var(--teal)" in val:
                        bg_kept_accent = True
                    continue
                d = dark_bg(rgb, selector)
                if d:
                    new.append(f"background: {d}{imp}")
                else:
                    bg_kept_accent = True
        for prop, val in decls:
            imp = " !important" if "!important" in val else ""
            if prop == "color" and not bg_kept_accent:
                d = dark_text(val)
                if d:
                    new.append(f"color: {d}{imp}")
            elif prop in ("border", "border-top", "border-bottom", "border-left", "border-right", "border-color"):
                colors = re.findall(r"(#[0-9a-fA-F]{3,6}|var\(--(?:ivory|line|white)\)|white|rgba?\([^)]*\))", val)
                for c in colors:
                    rgb = rgb_of(c)
                    if rgb and lum(rgb) > 0.6:
                        side = "" if prop in ("border", "border-color") else prop.replace("border", "")
                        new.append(f"border{side}-color: #2C4D53{imp}")
                        break
        if new:
            sel = ", ".join(f"{PREFIX} {s.strip()}" for s in selector.split(","))
            out.append(f"{sel} {{ {'; '.join(new)}; }}")
            count += 1

# Hand-tuned extras
out += [
    f"{PREFIX} .site-header {{ background: rgba(15, 37, 41, .94); border-bottom-color: #2C4D53; }}",
    f"{PREFIX} .brand-copy, {PREFIX} .brand-copy strong {{ color: #E6EFEB; }}",
    f"{PREFIX} .brand-mark svg {{ stroke: #A8CFC3; }}",
    f"{PREFIX} .menu-toggle span {{ background: #E6EFEB; }}",
    f"{PREFIX} h1, {PREFIX} h2, {PREFIX} h3 {{ color: #E6EFEB; }}",
    f"{PREFIX} h1 em, {PREFIX} h2 em, {PREFIX} .page-head h1 em {{ color: #A8CFC3; }}",
    f"{PREFIX} .eyebrow {{ color: #A8CFC3; }}",
    f"{PREFIX} input, {PREFIX} select, {PREFIX} textarea {{ background: #102A2F; color: #E6EFEB; border-color: #2C4D53; }}",
    f"{PREFIX} .map-frame {{ filter: brightness(.85); }}",
]
(ROOT / "src/app/theme.css").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote src/app/theme.css with {count} generated rules")
